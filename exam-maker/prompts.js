// 첫 메시지 주문서
export function buildOrderForm(s, fileSummary) {
  const lines = [
    '# 출제 주문서',
    '',
    `- 학교/학년: ${s.school || '(미입력)'} / ${s.grade}`,
    `- 과목: ${s.subject}`,
    `- 시험: ${s.examName || '(미입력)'}`,
    `- 출제 범위: ${s.range || '(첨부한 교과서 단원 전체)'}`,
    `- 문항 수: 선택형 ${s.mcq}문항, 서술형 ${s.essay}문항 (총 ${Number(s.mcq) + Number(s.essay)}문항)`,
    `- 총점: ${s.total}점${s.scoreRule ? ` (배점 규칙: ${s.scoreRule})` : ''}`,
    `- 난이도 비율(상:중:하): ${s.diffHigh}:${s.diffMid}:${s.diffLow}`,
    `- 선택형 선지 수: ${s.choices}지선다`,
  ];
  if (s.extra) lines.push(`- 추가 요청: ${s.extra}`);
  lines.push('', '## 첨부 자료', fileSummary || '(첨부 없음)', '');
  lines.push('위 자료를 모두 읽고, 바로 출제하지 말고 1단계 "자료 분석 보고"부터 해 주세요.');
  return lines.join('\n');
}

