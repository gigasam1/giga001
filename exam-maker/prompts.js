// 첫 메시지 주문서
export function buildOrderForm(s, fileSummary, auto) {
  const lines = [
    '# 출제 주문서',
    '',
    `- 학교/학년: ${s.school || '(미입력)'} / ${s.grade}`,
    `- 과목: ${s.subject}`,
    `- 시험: ${s.examName || '(미입력)'}`,
    `- 출제 범위: ${s.range || '(첨부한 학습 내용 전체)'}`,
  ];
  if (s.lesson) lines.push(`- 이번 학습 내용 요약: ${s.lesson}`);
  lines.push(
    `- 문항 수: 선택형 ${s.mcq}문항, 서술형 ${s.essay}문항 (총 ${Number(s.mcq) + Number(s.essay)}문항)`,
    `- 총점: ${s.total}점${s.scoreRule ? ` (배점 규칙: ${s.scoreRule})` : ''}`,
    `- 난이도: ${s.diffPreset || '직접 설정'} — 상:중:하 = ${s.diffHigh}:${s.diffMid}:${s.diffLow}`,
    `- 선택형 선지 수: ${s.choices}지선다`,
  );
  if (s.extra) lines.push(`- 추가 요청: ${s.extra}`);
  lines.push('', '## 첨부 자료', fileSummary || '(첨부 없음)', '');
  if (auto) {
    lines.push(`## 자동 출제
교사 확인 없이 한 번에 진행합니다. 1단계 자료 분석 보고는 10줄 이내로 요약하고, 곧바로 2단계 출제까지 마친 뒤 출력 형식의 다섯 제목(${HEADINGS})을 그대로 써서 최종 산출물을 내 주세요.`);
  } else {
    lines.push('위 자료를 모두 읽고, 바로 출제하지 말고 1단계 "자료 분석 보고"부터 해 주세요.');
  }
  return lines.join('\n');
}

